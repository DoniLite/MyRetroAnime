import { useEffect, useMemo, useState } from "react";
import {
	BufferAttribute,
	Color,
	DoubleSide,
	InstancedBufferAttribute,
	InstancedBufferGeometry,
	InstancedMesh,
	Matrix4,
	Mesh,
	MeshStandardMaterial,
	Quaternion,
	RepeatWrapping,
	ShaderMaterial,
	SRGBColorSpace,
	type Texture,
	TextureLoader,
	Vector3,
} from "three";
import { GLTFLoader } from "three/examples/jsm/loaders/GLTFLoader.js";
import type { Stop } from "../types";
import { type Placement, scatterVegetation } from "./scatter";
import * as glsl from "./shaders";
import {
	colorAt,
	heightAt,
	random,
	riverAt,
	TRACK_EDGE_Z,
	WATER_Y,
} from "./terrain";

/** Phones get half the vegetation. */
const density = () => (matchMedia("(pointer: coarse)").matches ? 0.5 : 1);

/** Which bark and leaf textures each generated species uses (public/textures/2026/trees/). */
const OAK = { bark: "oak", leaf: "oak" };
const SPECIES: Record<string, { bark: string; leaf: string }> = {
	oak: OAK,
	oak_large: OAK,
	aspen: { bark: "birch", leaf: "aspen" },
	pine: { bark: "pine", leaf: "pine" },
	pine_large: { bark: "pine", leaf: "pine" },
	bush: OAK,
};

/**
 * Foliage tint per season; the leaf textures are grayscale so one model serves every season.
 * Missing means bare branches: deciduous trees lose their leaves in winter.
 */
const FOLIAGE: Record<string, Partial<Record<string, string>>> = {
	winter: { pine: "#8ea598" },
	spring: {
		oak: "#ffd3e0",
		aspen: "#c9ec8a",
		pine: "#6e9460",
		bush: "#acd67a",
	},
	summer: {
		oak: "#84b65a",
		aspen: "#a2cc62",
		pine: "#5d8452",
		bush: "#82ae56",
	},
	fall: { oak: "#e8823f", aspen: "#f4c95a", pine: "#667a4c", bush: "#cc8644" },
};

const textures = new Map<string, Texture>();
function treeTexture(file: string, color: boolean) {
	let texture = textures.get(file);
	if (!texture) {
		texture = new TextureLoader().load(`/textures/2026/trees/${file}`);
		texture.wrapS = texture.wrapT = RepeatWrapping;
		texture.anisotropy = 4;
		if (color) texture.colorSpace = SRGBColorSpace;
		textures.set(file, texture);
	}
	return texture;
}

const materials = new Map<string, MeshStandardMaterial>();
function material(key: string, make: () => MeshStandardMaterial) {
	let found = materials.get(key);
	if (!found) {
		found = make();
		materials.set(key, found);
	}
	return found;
}

function barkMaterial(bark: string) {
	return material(
		`bark:${bark}`,
		() =>
			new MeshStandardMaterial({
				map: treeTexture(`bark_${bark}_color.jpg`, true),
				normalMap: treeTexture(`bark_${bark}_normal.jpg`, false),
				roughness: 0.95,
			}),
	);
}

function leafMaterial(leaf: string, tint: string) {
	return material(
		`leaf:${leaf}:${tint}`,
		() =>
			new MeshStandardMaterial({
				map: treeTexture(`leaf_${leaf}.png`, true),
				color: new Color(tint),
				// Light passing through the leaves: foliage seen against the sun never turns to a dark blot.
				emissive: new Color(tint),
				emissiveIntensity: 0.3,
				alphaTest: 0.5,
				side: DoubleSide,
				roughness: 0.8,
			}),
	);
}

/**
 * Every tree and bush of the line: realistic trees generated by ez-tree (scripts/trees.ts),
 * one InstancedMesh per part, model, season and stretch of line.
 */
export function Forest({ stops, length }: { stops: Stop[]; length: number }) {
	const [meshes, setMeshes] = useState<InstancedMesh[]>([]);

	useEffect(() => {
		let cancelled = false;
		// load() rather than loadAsync(): the callback runs before the loading manager marks the model
		// done, so the leaf and bark textures queued here keep the scene's "fully loaded" signal waiting.
		new GLTFLoader().load(
			"/models/2026/trees.glb",
			(gltf) => {
				if (cancelled) return;
				const groups = new Map<string, Placement[]>();
				for (const placement of scatterVegetation(stops, length, density())) {
					// Chunks along the line keep each InstancedMesh local, so off-screen ones are culled.
					const key = `${placement.season}:${placement.name}:${Math.floor(placement.x / 240)}`;
					groups.set(key, [...(groups.get(key) ?? []), placement]);
				}

				const built: InstancedMesh[] = [];
				const matrix = new Matrix4();
				const position = new Vector3();
				const rotation = new Quaternion();
				const scale = new Vector3();
				const up = new Vector3(0, 1, 0);
				gltf.scene.updateMatrixWorld(true);

				for (const [key, items] of groups) {
					const [season, name] = key.split(":") as [string, string, string];
					const species = name.replace(/_\d+$/, "");
					const { bark, leaf } = SPECIES[species] ?? OAK;
					const tint = FOLIAGE[season]?.[species.replace("_large", "")];
					const parts: [string, MeshStandardMaterial | undefined][] = [
						["branches", barkMaterial(bark)],
						["leaves", tint ? leafMaterial(leaf, tint) : undefined],
					];
					for (const [part, partMaterial] of parts) {
						const node = gltf.scene.getObjectByName(`${name}_${part}`);
						if (!(node instanceof Mesh) || !partMaterial) continue;
						const mesh = new InstancedMesh(
							node.geometry,
							partMaterial,
							items.length,
						);
						items.forEach((p, i) => {
							position.set(p.x, p.y, p.z);
							rotation.setFromAxisAngle(up, p.rotation);
							scale.setScalar(p.scale);
							// The node matrix also undoes the quantization of the vertices.
							mesh.setMatrixAt(
								i,
								matrix
									.compose(position, rotation, scale)
									.multiply(node.matrixWorld),
							);
						});
						mesh.computeBoundingSphere();
						built.push(mesh);
					}
				}
				setMeshes(built);
			},
			undefined,
			(error) => console.warn("Vegetation failed to load", error),
		);
		return () => {
			cancelled = true;
		};
	}, [stops, length]);

	return (
		<>
			{meshes.map((mesh) => (
				<primitive key={mesh.uuid} object={mesh} />
			))}
		</>
	);
}

/** Tens of thousands of blades along the track, colored by the season of their stretch. */
export function Grass({
	stops,
	length,
	shared,
}: {
	stops: Stop[];
	length: number;
	shared: {
		uTime: { value: number };
		uCamX: { value: number };
		uHaze: { value: Color };
		uFogDensity: { value: number };
	};
}) {
	const geometry = useMemo(() => {
		const blade = new InstancedBufferGeometry();
		const w = 0.05;
		blade.setAttribute(
			"position",
			new BufferAttribute(
				new Float32Array([
					-w,
					0,
					0,
					w,
					0,
					0,
					-w * 0.6,
					0.5,
					0,
					w * 0.6,
					0.5,
					0,
					0,
					1,
					0,
				]),
				3,
			),
		);
		blade.setAttribute(
			"uv",
			new BufferAttribute(
				new Float32Array([0, 0, 1, 0, 0, 0.5, 1, 0.5, 0.5, 1]),
				2,
			),
		);
		blade.setIndex([0, 1, 2, 2, 1, 3, 2, 3, 4]);

		const count = Math.round(16000 * density());
		const offsets = new Float32Array(count * 3);
		const colors = new Float32Array(count * 3);
		const scales = new Float32Array(count);
		const rand = random(26);
		const color = new Color();
		let placed = 0;
		for (let n = 0; n < count * 2 && placed < count; n++) {
			const x = -60 + rand() * (length + 120);
			const z = TRACK_EDGE_Z - 0.3 - 40 * rand() ** 1.4;
			const y = heightAt(x, z);
			const shade = 0.8 + rand() * 0.35;
			const river = riverAt(x);
			// Reeds: the blades grow taller along the water's edge.
			const reeds =
				Math.abs(TRACK_EDGE_Z - z - river.center) < river.halfWidth + 2.5
					? 1.9
					: 1;
			const height = (0.45 + rand() * 0.55) * reeds;
			if (y < WATER_Y + 0.05) continue;
			colorAt(stops, x, "ground", color).multiplyScalar(shade);
			offsets.set([x, y - 0.05, z], placed * 3);
			colors.set([color.r, color.g, color.b], placed * 3);
			scales[placed] = height;
			placed++;
		}
		blade.setAttribute("aOffset", new InstancedBufferAttribute(offsets, 3));
		blade.setAttribute("aColor", new InstancedBufferAttribute(colors, 3));
		blade.setAttribute("aScale", new InstancedBufferAttribute(scales, 1));
		blade.instanceCount = placed;
		return blade;
	}, [stops, length]);

	const material = useMemo(
		() =>
			new ShaderMaterial({
				vertexShader: glsl.grassVertex,
				fragmentShader: glsl.grassFragment,
				side: DoubleSide,
				uniforms: {
					uTime: shared.uTime,
					uCamX: shared.uCamX,
					uWind: { value: 0.12 },
					uFog: shared.uHaze,
					uFogDensity: shared.uFogDensity,
				},
			}),
		[shared],
	);

	return <mesh geometry={geometry} material={material} frustumCulled={false} />;
}
